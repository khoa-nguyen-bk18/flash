#!/usr/bin/env python3
"""
Interactive Keystore creation wizard and signing configuration helper.
"""

import os
import sys
import subprocess
from pathlib import Path
from core.config import ConfigManager
from core import ui

def run_keystore_create():
    cfg = ConfigManager.get_instance()
    try:
        keytool = cfg.get_keytool_path()
    except Exception as e:
        ui.error(f"Lỗi tìm keytool: {e}")
        return

    ui.header("Trình tạo Keystore Android (Keytool Wizard)")
    ui.info("Tạo file khóa bảo mật (.jks) để ký các bản Release APK.\n")

    # 1. Output path
    default_dir = cfg.project_root / "signing"
    default_dir.mkdir(parents=True, exist_ok=True)
    default_path = default_dir / "release.jks"
    out_path_str = ui.ask_input("Đường dẫn lưu Keystore", str(default_path))
    out_path = Path(out_path_str).resolve()

    if out_path.exists():
        overwrite = ui.ask_confirm(f"File {out_path.name} đã tồn tại! Bạn có muốn ghi đè không?", default=False)
        if not overwrite:
            ui.info("Đã hủy tạo keystore.")
            return

    # 2. Key Alias
    alias = ui.ask_input("Key Alias", "release-key")
    while not alias:
        alias = ui.ask_input("Key Alias không được để trống", "release-key")

    # 3. Store Password
    store_pass = ui.ask_input("Mật khẩu Keystore (tối thiểu 6 ký tự)")
    while len(store_pass) < 6:
        ui.warning("Mật khẩu phải có ít nhất 6 ký tự!")
        store_pass = ui.ask_input("Mật khẩu Keystore (tối thiểu 6 ký tự)")

    store_pass_confirm = ui.ask_input("Xác nhận lại mật khẩu Keystore")
    if store_pass != store_pass_confirm:
        ui.error("Mật khẩu xác nhận không khớp! Hủy bỏ.")
        return

    # 4. Key Password
    same_pass = ui.ask_confirm("Sử dụng cùng mật khẩu cho Key Alias?", default=True)
    if same_pass:
        key_pass = store_pass
    else:
        key_pass = ui.ask_input("Mật khẩu cho Key Alias (tối thiểu 6 ký tự)")
        while len(key_pass) < 6:
            key_pass = ui.ask_input("Mật khẩu cho Key Alias (tối thiểu 6 ký tự)")

    # 5. Certificate Info
    cn = ui.ask_input("Họ và Tên / Tổ chức phát triển (CN)", "Developer")
    ou = ui.ask_input("Đơn vị / Phòng ban (OU)", "Mobile Team")
    org = ui.ask_input("Tên Công ty / Doanh nghiệp (O)", "Organization")
    city = ui.ask_input("Thành phố (L)", "Hanoi")
    country = ui.ask_input("Mã Quốc gia 2 chữ cái (C)", "VN")

    dname = f"CN={cn}, OU={ou}, O={org}, L={city}, C={country}"

    ui.info("Đang tạo Keystore bằng JDK keytool...")
    cmd = [
        keytool,
        "-genkeypair",
        "-v",
        "-keystore", str(out_path),
        "-alias", alias,
        "-keyalg", "RSA",
        "-keysize", "2048",
        "-validity", "10000",
        "-storepass", store_pass,
        "-keypass", key_pass,
        "-dname", dname
    ]

    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode == 0:
        ui.success(f"Tạo Keystore thành công tại: {ui.Colors.BOLD}{out_path}{ui.Colors.RESET}")
        ui.detail("Key Alias", alias)
        ui.detail("Thời hạn", "10,000 ngày (~27 năm)")

        # Offer to write to local.properties
        save_props = ui.ask_confirm("Bạn có muốn lưu cấu hình này vào file local.properties để tự động ký không?", default=True)
        if save_props:
            local_props = cfg.project_root / "local.properties"
            rel_path = os.path.relpath(out_path, cfg.project_root)
            config_lines = [
                f"\n# Keystore Configuration generated by Flash CLI",
                f"RELEASE_KEYSTORE_PATH={rel_path}",
                f"RELEASE_KEY_ALIAS={alias}",
                f"RELEASE_STORE_PASSWORD={store_pass}",
                f"RELEASE_KEY_PASSWORD={key_pass}\n"
            ]
            try:
                with open(local_props, "a", encoding="utf-8") as f:
                    f.write("\n".join(config_lines))
                ui.success("Đã lưu thông tin ký vào local.properties!")
            except Exception as e:
                ui.warning(f"Không thể ghi vào local.properties: {e}")
    else:
        ui.error(f"Tạo Keystore thất bại:\n{res.stderr}")
